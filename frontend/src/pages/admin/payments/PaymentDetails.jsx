import { useEffect, useState } from "react";
import { motion } from "framer-motion";
import {
    ArrowLeft,
    CheckCircle2,
    Clock3,
    CreditCard,
    FileText,
    RefreshCw,
    RotateCcw,
    User,
    XCircle,
    Download,
    Loader2,
} from "lucide-react";
import {
    useNavigate,
    useParams,
} from "react-router-dom";
import toast from "react-hot-toast";

import PageHeader from "../../../components/layout/PageHeader";
import paymentService from "../../../services/paymentService";
import api from "../../../services/api";

// =========================================================
// HELPERS
// =========================================================

const formatCurrency = (value = 0) => {
    return `₹${Number(value || 0).toLocaleString(
        "en-IN",
        {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
        }
    )}`;
};

const getStatus = (payment) =>
    String(
        payment?.status ||
        payment?.payment_status ||
        ""
    ).toLowerCase();

const getInvoiceNumber = (payment) =>
    payment?.invoice?.invoice_number ||
    payment?.invoice?.number ||
    payment?.invoice_number ||
    payment?.invoiceNumber ||
    payment?.invoice ||
    "-";

const getCustomerName = (payment) =>
    payment?.client?.name ||
    payment?.customer?.name ||
    payment?.client_name ||
    payment?.customer_name ||
    payment?.customer ||
    "-";

// =========================================================
// COMPONENT
// =========================================================

export default function PaymentDetails() {
    const navigate = useNavigate();

    const { id } = useParams();

    const [payment, setPayment] =
        useState(null);

    const [loading, setLoading] =
        useState(true);

    const loadPayment = async () => {
        try {
            setLoading(true);

            const data =
                await paymentService.get(id);

            setPayment(data);
        } catch (error) {
            console.error(
                "Payment details error:",
                error
            );

            toast.error(
                error?.response?.data?.detail ||
                error?.response?.data?.message ||
                "Unable to load payment"
            );
        } finally {
            setLoading(false);
        }
    };

    const handleDownloadPdf = async () => {
        try {
            const toastId = toast.loading("Generating receipt PDF...");
            
            // Generate payment receipt as text document
            const receiptContent = `
===========================================
              PAYMENT RECEIPT
===========================================

Payment ID: PAY-${payment.id || payment.payment_id}
Date: ${new Date().toLocaleDateString()}

PAYMENT DETAILS
---------------
Amount: ${formatCurrency(payment.amount || payment.paid_amount || 0)}
Method: ${payment.method || payment.payment_method || 'N/A'}
Transaction ID: ${payment.transaction_id || payment.transactionId || 'N/A'}
Status: ${payment.status || 'completed'}

INVOICE DETAILS
--------------
Invoice: ${payment.invoice?.invoice_number || payment.invoice_number || 'N/A'}
Customer: ${payment.client?.name || payment.customer?.name || 'N/A'}

-------------------------------------------
Generated by InvoiceFlow
            `.trim();

            const blob = new Blob([receiptContent], { type: 'text/plain' });
            const url = window.URL.createObjectURL(blob);
            const link = document.createElement('a');
            link.href = url;
            link.setAttribute('download', `payment_receipt_${payment.id || payment.payment_id}.txt`);
            document.body.appendChild(link);
            link.click();
            link.remove();
            window.URL.revokeObjectURL(url);
            
            toast.success("Receipt downloaded successfully!", { id: toastId });
        } catch (error) {
            console.error("Download error:", error);
            toast.error("Failed to download receipt");
        }
    };

    useEffect(() => {
        if (id) {
            loadPayment();
        }
    }, [id]);

    // =======================================================
    // LOADING
    // =======================================================

    if (loading) {
        return (
            <div className="flex min-h-[500px] items-center justify-center">
                <div className="text-center">
                    <RefreshCw
                        size={30}
                        className="mx-auto animate-spin text-slate-400"
                    />

                    <p className="mt-3 text-sm text-slate-500">
                        Loading payment...
                    </p>
                </div>
            </div>
        );
    }

    if (!payment) {
        return (
            <div className="flex min-h-[500px] items-center justify-center">
                <div className="text-center">
                    <XCircle
                        size={42}
                        className="mx-auto text-red-400"
                    />

                    <h2 className="mt-4 text-xl font-bold text-slate-900">
                        Payment not found
                    </h2>

                    <button
                        onClick={() =>
                            navigate(
                                "/admin/payments"
                            )
                        }
                        className="mt-5 rounded-xl bg-slate-900 px-5 py-3 text-sm font-bold text-white"
                    >
                        Back to Payments
                    </button>
                </div>
            </div>
        );
    }

    const status =
        getStatus(payment);

    const amount =
        payment.amount ||
        payment.paid_amount ||
        payment.total ||
        0;

    const paymentId =
        payment.id ||
        payment.payment_id;

    const transactionId =
        payment.transaction_id ||
        payment.transactionId ||
        payment.razorpay_payment_id ||
        "-";

    const invoiceId =
        payment.invoice?.id ||
        payment.invoice_id;

    // =======================================================
    // UI
    // =======================================================

    return (
        <motion.div
            initial={{
                opacity: 0,
                y: 15,
            }}
            animate={{
                opacity: 1,
                y: 0,
            }}
            className="space-y-6"
        >
            <PageHeader
                title={`Payment PAY-${paymentId}`}
                subtitle="View complete payment and transaction information."
                action={
                    <div className="flex items-center gap-3">
                        <button
                            onClick={handleDownloadPdf}
                            className="flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-4 py-2.5 text-sm font-semibold text-slate-700 shadow-sm hover:bg-slate-50"
                        >
                            <Download size={16} />
                            Download Receipt
                        </button>
                        <button
                            onClick={() =>
                                navigate(
                                    "/admin/payments"
                                )
                            }
                            className="flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-4 py-2.5 text-sm font-semibold text-slate-700 shadow-sm hover:bg-slate-50"
                        >
                            <ArrowLeft size={16} />

                            Back to Payments
                        </button>
                    </div>
                }
            />

            {/* =================================================
          TOP PAYMENT CARD
      ================================================= */}

            <div className="grid gap-6 lg:grid-cols-[1fr_360px]">
                <div className="overflow-hidden rounded-3xl border border-slate-200 bg-white shadow-sm">
                    <div className="border-b border-slate-100 p-6">
                        <div className="flex flex-col gap-5 sm:flex-row sm:items-center sm:justify-between">
                            <div>
                                <p className="text-xs font-semibold uppercase tracking-widest text-slate-400">
                                    Payment ID
                                </p>

                                <h1 className="mt-1 text-2xl font-black text-slate-900">
                                    PAY-{paymentId}
                                </h1>
                            </div>

                            <PaymentStatus
                                status={status}
                            />
                        </div>
                    </div>

                    <div className="p-6">
                        {/* AMOUNT */}

                        <div className="rounded-3xl bg-slate-900 p-7 text-white">
                            <p className="text-xs font-semibold uppercase tracking-wider text-slate-400">
                                Amount
                            </p>

                            <p className="mt-2 text-4xl font-black">
                                {formatCurrency(amount)}
                            </p>

                            <p className="mt-2 text-sm text-slate-400">
                                {payment.currency ||
                                    "INR"}
                            </p>
                        </div>

                        {/* DETAILS */}

                        <div className="mt-6 grid gap-4 sm:grid-cols-2">
                            <DetailCard
                                label="Invoice"
                                value={getInvoiceNumber(
                                    payment
                                )}
                                icon={FileText}
                            />

                            <DetailCard
                                label="Customer"
                                value={getCustomerName(
                                    payment
                                )}
                                icon={User}
                            />

                            <DetailCard
                                label="Payment Method"
                                value={
                                    payment.payment_method ||
                                    payment.method ||
                                    "Online"
                                }
                                icon={CreditCard}
                            />

                            <DetailCard
                                label="Gateway"
                                value={
                                    payment.gateway ||
                                    "Razorpay"
                                }
                                icon={CreditCard}
                            />

                            <DetailCard
                                label="Transaction ID"
                                value={transactionId}
                                icon={CheckCircle2}
                            />

                            <DetailCard
                                label="Created"
                                value={
                                    payment.created_at
                                        ? new Date(
                                            payment.created_at
                                        ).toLocaleString(
                                            "en-IN"
                                        )
                                        : payment.date ||
                                        "-"
                                }
                                icon={Clock3}
                            />
                        </div>
                    </div>
                </div>

                {/* =================================================
            SUMMARY
        ================================================= */}

                <div className="space-y-6">
                    <div className="rounded-3xl border border-slate-200 bg-white p-6 shadow-sm">
                        <h2 className="font-bold text-slate-900">
                            Payment Summary
                        </h2>

                        <div className="mt-5 space-y-4">
                            <SummaryRow
                                label="Invoice"
                                value={getInvoiceNumber(
                                    payment
                                )}
                            />

                            <SummaryRow
                                label="Amount"
                                value={formatCurrency(
                                    amount
                                )}
                            />

                            <SummaryRow
                                label="Method"
                                value={
                                    payment.payment_method ||
                                    payment.method ||
                                    "Online"
                                }
                            />

                            <SummaryRow
                                label="Gateway"
                                value={
                                    payment.gateway ||
                                    "Razorpay"
                                }
                            />

                            <div className="border-t border-slate-100 pt-4">
                                <SummaryRow
                                    label="Status"
                                    value={
                                        <PaymentStatus
                                            status={status}
                                        />
                                    }
                                />
                            </div>
                        </div>
                    </div>

                    {/* CUSTOMER */}

                    <div className="rounded-3xl border border-slate-200 bg-white p-6 shadow-sm">
                        <div className="flex items-center gap-3">
                            <div className="flex h-11 w-11 items-center justify-center rounded-2xl bg-slate-100">
                                <User
                                    size={20}
                                    className="text-slate-600"
                                />
                            </div>

                            <div>
                                <p className="text-xs text-slate-400">
                                    Customer
                                </p>

                                <p className="font-bold text-slate-900">
                                    {getCustomerName(
                                        payment
                                    )}
                                </p>
                            </div>
                        </div>

                        {(
                            payment.client?.email ||
                            payment.customer?.email ||
                            payment.client_email ||
                            payment.customer_email
                        ) && (
                                <p className="mt-4 text-sm text-slate-500">
                                    {payment.client?.email ||
                                        payment.customer?.email ||
                                        payment.client_email ||
                                        payment.customer_email}
                                </p>
                            )}
                    </div>
                </div>
            </div>

            {/* =================================================
          TRANSACTION INFORMATION
      ================================================= */}

            <div className="rounded-3xl border border-slate-200 bg-white shadow-sm">
                <div className="border-b border-slate-100 p-6">
                    <h2 className="font-bold text-slate-900">
                        Transaction Information
                    </h2>
                </div>

                <div className="grid gap-0 md:grid-cols-2">
                    <TransactionRow
                        label="Payment ID"
                        value={`PAY-${paymentId}`}
                    />

                    <TransactionRow
                        label="Transaction ID"
                        value={transactionId}
                    />

                    <TransactionRow
                        label="Razorpay Order ID"
                        value={
                            payment.razorpay_order_id ||
                            payment.order_id ||
                            "-"
                        }
                    />

                    <TransactionRow
                        label="Razorpay Payment ID"
                        value={
                            payment.razorpay_payment_id ||
                            "-"
                        }
                    />

                    <TransactionRow
                        label="Payment Method"
                        value={
                            payment.payment_method ||
                            payment.method ||
                            "-"
                        }
                    />

                    <TransactionRow
                        label="Currency"
                        value={
                            payment.currency ||
                            "INR"
                        }
                    />

                    <TransactionRow
                        label="Created At"
                        value={
                            payment.created_at
                                ? new Date(
                                    payment.created_at
                                ).toLocaleString(
                                    "en-IN"
                                )
                                : "-"
                        }
                    />

                    <TransactionRow
                        label="Updated At"
                        value={
                            payment.updated_at
                                ? new Date(
                                    payment.updated_at
                                ).toLocaleString(
                                    "en-IN"
                                )
                                : "-"
                        }
                    />
                </div>
            </div>

            {/* =================================================
          ACTIONS
      ================================================= */}

            <div className="flex flex-wrap gap-3">
                {invoiceId && (
                    <button
                        onClick={() =>
                            navigate(
                                `/admin/invoices/${invoiceId}`
                            )
                        }
                        className="flex items-center gap-2 rounded-xl border border-slate-200 bg-white px-5 py-3 text-sm font-bold text-slate-700 hover:bg-slate-50"
                    >
                        <FileText size={17} />

                        View Invoice
                    </button>
                )}

                <button
                    onClick={() =>
                        navigate(
                            "/admin/payments"
                        )
                    }
                    className="flex items-center gap-2 rounded-xl bg-slate-900 px-5 py-3 text-sm font-bold text-white hover:bg-slate-800"
                >
                    <ArrowLeft size={17} />

                    Back to Payments
                </button>
            </div>
        </motion.div>
    );
}

// =========================================================
// DETAIL CARD
// =========================================================

function DetailCard({
    label,
    value,
    icon: Icon,
}) {
    return (
        <div className="rounded-2xl border border-slate-200 p-4">
            <div className="flex items-center gap-3">
                <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-slate-100">
                    <Icon
                        size={16}
                        className="text-slate-600"
                    />
                </div>

                <div className="min-w-0">
                    <p className="text-xs text-slate-400">
                        {label}
                    </p>

                    <p className="mt-1 truncate text-sm font-bold text-slate-900">
                        {value}
                    </p>
                </div>
            </div>
        </div>
    );
}

// =========================================================
// SUMMARY ROW
// =========================================================

function SummaryRow({
    label,
    value,
}) {
    return (
        <div className="flex items-center justify-between gap-4">
            <span className="text-sm text-slate-500">
                {label}
            </span>

            <span className="text-right text-sm font-bold text-slate-900">
                {value}
            </span>
        </div>
    );
}

// =========================================================
// TRANSACTION ROW
// =========================================================

function TransactionRow({
    label,
    value,
}) {
    return (
        <div className="border-b border-slate-100 p-5 last:border-0 md:nth-[even]:border-l">
            <p className="text-xs font-semibold uppercase tracking-wider text-slate-400">
                {label}
            </p>

            <p className="mt-2 break-all text-sm font-semibold text-slate-800">
                {value}
            </p>
        </div>
    );
}

// =========================================================
// STATUS
// =========================================================

function PaymentStatus({ status }) {
    if (
        ["success", "paid", "completed"].includes(
            status
        )
    ) {
        return (
            <span className="inline-flex items-center gap-2 rounded-full border border-emerald-100 bg-emerald-50 px-3 py-1.5 text-xs font-bold text-emerald-700">
                <CheckCircle2 size={14} />

                SUCCESS
            </span>
        );
    }

    if (status === "failed") {
        return (
            <span className="inline-flex items-center gap-2 rounded-full border border-red-100 bg-red-50 px-3 py-1.5 text-xs font-bold text-red-700">
                <XCircle size={14} />

                FAILED
            </span>
        );
    }

    if (status === "refunded") {
        return (
            <span className="inline-flex items-center gap-2 rounded-full border border-purple-100 bg-purple-50 px-3 py-1.5 text-xs font-bold text-purple-700">
                <RotateCcw size={14} />

                REFUNDED
            </span>
        );
    }

    return (
        <span className="inline-flex items-center gap-2 rounded-full border border-amber-100 bg-amber-50 px-3 py-1.5 text-xs font-bold text-amber-700">
            <Clock3 size={14} />

            PENDING
        </span>
    );
}